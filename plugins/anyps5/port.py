"""Converts a PS5 dump with the AnyPS5 relinker on first start, then runs it.

Runs as the game process (inside gamescope), so the conversion happens while
the launch screen is shown and its log ends up in the frontend's game log.
Stdlib only – it must not depend on the frontend being importable.

Expected game folder (on the exFAT userdata partition, so no symlinks):

    roms/ps5/<Spiel>.ps5/
        app0/                 decrypted dump: eboot.bin (ELF), sce_module/, sce_sys/param.json, data …

After the first start:

    <Spiel>.ps5/app.elf       native Linux executable
    <Spiel>.ps5/app0/sce_module/   converted modules (runtime layout of AnyPS5)
    <Spiel>.ps5/.anyps5/input/     the original modules, moved (not copied) out of app0/
    <Spiel>.ps5/.anyps5/manifest.json, convert.log

``--restore`` moves the original modules back and removes the generated files.
"""
import argparse
import json
import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

MODULE_DIRS = ("sce_module", "sce_modules", "prx")
STATE = ".anyps5"


class PortError(RuntimeError):
    pass


def _stamp(path):
    st = os.stat(path)
    return [st.st_size, int(st.st_mtime)]


def is_converted(game):
    game = Path(game)
    return (game / STATE / "manifest.json").is_file() and (game / "app.elf").is_file()


def prepare(relinker_cmd, libs, game, to_intel=False, log=print):
    """Converts ``game`` if needed. Returns the path of the native executable."""
    game, libs = Path(game), Path(libs)
    app0, state = game / "app0", game / STATE
    eboot = app0 / "eboot.bin"
    if not eboot.is_file():
        raise PortError(f"{eboot} fehlt – der entschlüsselte Dump gehört nach '<Spiel>.ps5/app0/'.")
    with open(eboot, "rb") as f:
        if f.read(4) != b"\x7fELF":
            raise PortError("eboot.bin ist kein entschlüsseltes ELF (verschlüsselter SELF-Container?). "
                            "AnyPS5 braucht einen entschlüsselten Dump.")
    if not libs.is_dir():
        raise PortError(f"AnyPS5-Systembibliotheken fehlen ({libs}) – Emulator neu installieren.")
    relinker_cmd = [str(c) for c in relinker_cmd]
    out = game / "app.elf"
    key = {"relinker": _stamp(relinker_cmd[-1]), "eboot": _stamp(eboot), "to_intel": bool(to_intel),
           "libs": str(libs.resolve())}
    manifest = state / "manifest.json"
    if out.is_file() and manifest.is_file():
        try:
            if json.loads(manifest.read_text(encoding="utf-8")).get("key") == key:
                return out
        except ValueError:
            pass
        log("AnyPS5: Relinker oder Spiel hat sich geändert – konvertiere neu.")

    # Move the original modules out of app0/ (a rename on the same file system, no copy):
    # the relinker writes the converted modules to app0/<dir>/, which must not be its input.
    inputs = state / "input"
    inputs.mkdir(parents=True, exist_ok=True)
    for name in MODULE_DIRS:
        src, kept = app0 / name, inputs / name
        if src.is_dir() and not kept.exists():
            os.replace(src, kept)
            log(f"AnyPS5: Original-Module {name}/ nach {STATE}/input/ verschoben.")
    if not any((inputs / n).is_dir() for n in MODULE_DIRS):
        (inputs / "sce_module").mkdir()          # titles without bundled modules

    cmd = relinker_cmd + (["--to-intel"] if to_intel else []) + [
        "--rpath", str(libs.resolve()), "--sce-module-path", str(inputs), str(eboot), str(out)]
    log("AnyPS5: konvertiere – " + " ".join(cmd))
    proc = subprocess.run(cmd, cwd=str(game), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, errors="replace")
    (state / "convert.log").write_text(proc.stdout, encoding="utf-8")
    log(proc.stdout[-4000:])
    if proc.returncode != 0 or not out.is_file():
        raise PortError(f"Konvertierung fehlgeschlagen (Code {proc.returncode}), siehe {state / 'convert.log'}")
    try:
        out.chmod(out.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        pass   # exFAT: permissions come from the mount options
    manifest.write_text(json.dumps({"key": key, "command": cmd}, indent=1), encoding="utf-8")
    return out


def restore(game, log=print):
    """Undo ``prepare``: put the original modules back and delete generated files."""
    game = Path(game)
    app0, state = game / "app0", game / STATE
    inputs = state / "input"
    for name in MODULE_DIRS:
        kept = inputs / name
        if not kept.is_dir():
            continue
        converted = app0 / name
        if converted.exists():
            shutil.rmtree(converted)            # generated by the relinker
        if any(kept.iterdir()):
            os.replace(kept, converted)
        else:
            kept.rmdir()
    for p in (game / "app.elf",):
        if p.exists():
            p.unlink()
    for p in game.glob("app.*.toml"):
        p.unlink()
    shutil.rmtree(state, ignore_errors=True)
    log("AnyPS5: Originalzustand wiederhergestellt.")


def main(argv=None):
    ap = argparse.ArgumentParser(description="AnyPS5: PS5-Dump konvertieren und starten")
    ap.add_argument("--relinker", required=True)
    ap.add_argument("--libs", required=True)
    ap.add_argument("--game", required=True)
    ap.add_argument("--to-intel", action="store_true")
    ap.add_argument("--restore", action="store_true")
    ap.add_argument("--convert-only", action="store_true")
    args = ap.parse_args(argv)
    if args.restore:
        restore(args.game)
        return 0
    try:
        exe = prepare([args.relinker], args.libs, args.game, args.to_intel)
    except PortError as e:
        print(f"AnyPS5: {e}", file=sys.stderr)
        return 3
    if args.convert_only:
        return 0
    os.chdir(args.game)
    sys.stdout.flush()
    os.execv(str(exe), [str(exe)])   # replaces this process: the game is now the launched process


if __name__ == "__main__":
    sys.exit(main())
